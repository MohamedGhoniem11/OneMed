export const REPORT_TYPES = Object.freeze(["history", "labs", "clinical-summary", "audit", "population"]);

function csvEscape(value) {
  let text = value === null || value === undefined ? "" : String(value);
  // Prevent spreadsheet formula execution from user-controlled clinical text.
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

export function toCsv(rows) {
  if (!Array.isArray(rows) || !rows.length) return "";
  const headers = Object.keys(rows[0]);
  return [headers.join(","), ...rows.map((row) => headers.map((h) => csvEscape(row[h])).join(","))].join("\r\n");
}

function nameOf(patient, user) {
  return patient?.name || patient?.fullName || user?.name || patient?.id || "Unknown patient";
}

async function patientScope(req, patientId) {
  const patient = await getStore().get("patients", patientId);
  if (!patient) throw httpError(404, "Patient not found");
  await canReadPatient(req, patientId, { scope: "records" });
  const user = await getStore().get("users", patientId);
  return { patient, user, name: nameOf(patient, user) };
}

function fhirPatient(patient, user) {
  const [family, ...given] = String(patient.name || user?.name || "").trim().split(/\s+/);
  return {
    resourceType: "Patient",
    id: patient.id,
    name: [{ family: family || "Unknown", given: given.length ? given : ["Unknown"] }],
    gender: patient.gender || "unknown",
    birthDate: patient.dateOfBirth || patient.dob || undefined,
    telecom: [patient.phone, user?.email].filter(Boolean).map((value, i) => ({ system: i === 0 ? "phone" : "email", value })),
    address: patient.address ? [{ text: patient.address, city: patient.city }] : undefined,
  };
}

function fhirObservations(records) {
  return records.flatMap((record) => valuesOf(record).map((v) => ({
    resourceType: "Observation",
    id: `obs-${record.id}-${String(v.name).replace(/\W+/g, "-")}`.slice(0, 64),
    status: "final",
    code: { text: v.name },
    subject: { reference: `Patient/${record.patientId}` },
    effectiveDateTime: dateOf(record) || undefined,
    valueQuantity: typeof v.value === "number" ? { value: v.value, unit: v.unit || "1" } : { valueString: String(v.value) },
    interpretation: v.flag ? [{ coding: [{ code: v.flag }] }] : undefined,
    referenceRange: (v.referenceLow !== undefined || v.referenceHigh !== undefined)
      ? [{ low: v.referenceLow !== undefined ? { value: v.referenceLow } : undefined, high: v.referenceHigh !== undefined ? { value: v.referenceHigh } : undefined }]
      : undefined,
  })));
}

async function historyReport(req, patientId) {
  const { patient, user, name } = await patientScope(req, patientId);
  const recordsPage = await getStore().query("records", {
    where: [{ field: "patientId", op: "==", value: patientId }],
    orderBy: [{ field: "observedAt", direction: "desc" }],
    limit: 500,
  });
  const prescriptionsPage = await getStore().query("prescriptions", {
    where: [{ field: "patientId", op: "==", value: patientId }],
    limit: 200,
  });
  const records = recordsPage.items;
  const prescriptions = prescriptionsPage.items;
  const lines = [
    `Patient: ${name}`,
    `Blood group: ${patient.bloodGroup || "not recorded"}`,
    `Allergies: ${(patient.allergies || []).join(", ") || "none recorded"}`,
    `Conditions: ${(patient.chronicDiseases || patient.chronic_conditions || []).join(", ") || "none recorded"}`,
    "",
    `Clinical history (${records.length} records)`,
    ...records.slice(0, 40).map((r) => `${String(dateOf(r) || "").slice(0, 10)} ${r.title || r.type}: ${r.summary || valuesOf(r).map((v) => `${v.name}=${v.value}`).join(", ")}`),
    "",
    `Prescriptions (${prescriptions.length})`,
    ...prescriptions.slice(0, 20).map((rx) => `${String(rx.createdAt || "").slice(0, 10)} ${rx.status}: ${(rx.items || rx.medicines || []).map((m) => m.name).join(", ")}`),
    "Generated by OneMed. Not a substitute for clinical judgement.",
  ];
  const medications = [...new Set([
    ...(patient.activeMedications || []),
    ...prescriptions.flatMap((rx) => (rx.items || rx.medicines || []).map((m) => m.name || m.medicine_name)),
  ].filter(Boolean))];
  const supplemental = [
    ...(patient.allergies || []).map((code, i) => ({
      resourceType: "AllergyIntolerance", id: `allergy-${i}`, clinicalStatus: { coding: [{ code: "active" }] },
      code: { text: String(code) }, patient: { reference: `Patient/${patient.id}` },
    })),
    ...(patient.chronicDiseases || patient.chronic_conditions || []).map((code, i) => ({
      resourceType: "Condition", id: `condition-${i}`, clinicalStatus: { coding: [{ code: "active" }] },
      code: { text: String(code) }, subject: { reference: `Patient/${patient.id}` },
    })),
    ...medications.map((code, i) => ({
      resourceType: "MedicationStatement", id: `medication-${i}`, status: "active",
      medicationCodeableConcept: { text: String(code) }, subject: { reference: `Patient/${patient.id}` },
    })),
  ];
  const fhir = {
    resourceType: "Bundle",
    type: "collection",
    meta: { source: "onemed" },
    entry: [fhirPatient(patient, user), ...fhirObservations(records), ...supplemental].map((resource) => ({ resource })),
  };
  return {
    title: `Patient Medical History Report - ${name}`,
    lines,
    fhir,
    csv: toCsv(records.map((r) => ({
      date: dateOf(r) || "", type: r.type, title: r.title || "", summary: r.summary || "",
      institution: r.institutionId || "", status: r.status || "",
      values: valuesOf(r).map((v) => `${v.name}=${v.value}${v.unit}`).join("; "),
    }))),
  };
}

async function labsReport(req, patientId, institutionId) {
  const { patient, user, name } = await patientScope(req, patientId);
  const where = [{ field: "patientId", op: "==", value: patientId }];
  if (institutionId) where.push({ field: "institutionId", op: "==", value: institutionId });
  const { items } = await getStore().query("records", { where, limit: 500 });
  const rows = items.flatMap((r) => valuesOf(r).map((v) => ({
    date: String(dateOf(r) || "").slice(0, 10),
    lab: r.institutionId || "unknown",
    test: v.name,
    value: v.value,
    unit: v.unit,
    range: `${v.referenceLow ?? ""}-${v.referenceHigh ?? ""}`,
    interpretation: v.flag || "",
    technician: r.uploadedBy || "",
  })));
  const lines = [
    `Lab Results Report - ${name}`,
    `Accredited institution(s): ${[...new Set(items.map((r) => r.institutionId).filter(Boolean))].join(", ") || "not recorded"}`,
    `Patient ID: ${patientId}`,
    "",
    ...rows.slice(0, 45).map((row) => `${row.date} ${row.test}: ${row.value} ${row.unit} (${row.range}) ${row.interpretation} - ${row.lab}`),
    "Verified results only. Interpret with clinical context.",
  ];
  const fhir = {
    resourceType: "Bundle",
    type: "collection",
    entry: [
      { resource: fhirPatient(patient, user) },
      ...items.slice(0, 40).map((r) => ({
        resource: {
          resourceType: "DiagnosticReport",
          id: r.id,
          status: "final",
          code: { text: r.title || "Laboratory report" },
          subject: { reference: `Patient/${patientId}` },
          effectiveDateTime: dateOf(r) || undefined,
          result: fhirObservations([r]).map((o) => ({ reference: `Observation/${o.id}` })),
          conclusion: r.summary || undefined,
        },
      })),
      ...fhirObservations(items.slice(0, 40)).map((resource) => ({ resource })),
    ],
  };
  return { title: `Lab Results Report - ${name}`, lines, fhir, csv: toCsv(rows) };
}

async function clinicalSummaryReport(req, patientId) {
  const { name } = await patientScope(req, patientId);
  const summary = await clinicalSummary(req, patientId);
  const analytics = await patientAnalytics(req, patientId);
  const lines = [
    `Clinical Summary Report - ${name}`,
    `Confidence: ${summary.confidence} (${summary.mode})`,
    "",
    ...summary.text.split("\n"),
    "",
    `Health score: ${analytics.healthScore}% (${analytics.recordCount} records)`,
    `Abnormal results flagged: ${analytics.abnormalCount}`,
    `Allergies: ${analytics.allergies.join(", ") || "none recorded"}`,
    `Conditions: ${analytics.conditions.join(", ") || "none recorded"}`,
    `Source records: ${summary.sources.join("; ") || "none"}`,
    summary.disclaimer || "AI-generated navigation aid only. Not medical advice.",
  ];
  return {
    title: `Clinical Summary Report - ${name}`,
    lines,
    clipboard: summary.text,
    summary,
    csv: toCsv(Object.entries(analytics.indicators)
      .filter(([, v]) => v)
      .map(([key, v]) => ({ indicator: key, value: v.value, unit: v.unit || "", flag: v.flag || "" }))),
  };
}

async function auditReport(req) {
  if (req.user?.role !== "admin") throw httpError(403, "Admin only");
  const { items } = await getStore().query("accessLog", { limit: 500 });
  const consents = (await getStore().query("consents", { limit: 500 })).items;
  const deletions = (await getStore().query("deletionRequests", { limit: 500 })).items;
  const chain = await verifyChain();
  const securityEvents = items.filter((log) => /override|failed_login|mfa|ai_issue|deletion/i.test(log.action || ""));
  const rows = items.map((log) => ({
    timestamp: log.createdAt || log.timestamp || "",
    actor: log.actorId || "",
    role: log.actorRole || "",
    action: log.action || "",
    resource: `${log.resourceType || ""}/${log.resourceId || ""}`,
    patient: log.patientId || "",
    status: `hash:${String(log.hash || "missing").slice(0, 8)}`,
  }));
  for (const request of deletions) {
    rows.push({ timestamp: request.createdAt || "", actor: request.patientId || "", role: "patient", action: "deletion_requested", resource: "patient", patient: request.patientId || "", status: request.status || "pending" });
  }
  const lines = [
    "Audit & Compliance Report",
    `Access events: ${items.length}`,
    `Consent grants/revocations: ${consents.length}`,
    `Deletion requests: ${deletions.length}`,
    `Security events: ${securityEvents.length}`,
    `Hash-chain verification: ${chain.valid ? "PASS" : `FAIL (${chain.reason} at ${chain.brokenAt})`}`,
    `Generated: ${new Date().toISOString()}`,
    "",
    ...rows.slice(0, 45).map((r) => `${String(r.timestamp).slice(0, 19)} ${r.actor} (${r.role}) ${r.action} ${r.resource} - ${r.status}`),
    `EDP checklist: access logging [PASS], consent tracking [PASS], hash chain [${chain.valid ? "PASS" : "FAIL"}], patient deletion [available in-app].`,
  ];
  return { title: "Audit & Compliance Report", lines, csv: toCsv(rows) };
}

async function populationReport() {
  const stats = await populationAnalytics();
  const lines = [
    "Population Health Analytics Report (de-identified)",
    `Generated: ${stats.generatedAt}`,
    `Patients: ${stats.totalPatients}; Records: ${stats.totalRecords}`,
    "",
    `Patients by city: ${Object.entries(stats.patientsByCity).map(([k, v]) => `${k}=${v}`).join(", ")}`,
    `Condition counts: ${Object.entries(stats.conditionCounts).map(([k, v]) => `${k}=${v}`).join(", ") || "none"}`,
    `Visits by month: ${Object.entries(stats.visitsByMonth).map(([k, v]) => `${k}=${v}`).join(", ")}`,
    "",
    `Lab averages: ${Object.entries(stats.labAverages).slice(0, 12).map(([k, v]) => `${k}=${v}`).join(", ")}`,
    "No names, national IDs or phone numbers are included.",
  ];
  const rows = Object.entries(stats.labAverages).map(([test, average]) => ({ test, average }));
  return { title: "Population Health Analytics Report", lines, csv: toCsv(rows), json: stats };
}

/** Builds a report and returns it in the requested format. */
export async function buildReport(req, type, { patientId, format = "pdf", institutionId } = {}) {
  if (!REPORT_TYPES.includes(type)) throw httpError(400, `Unknown report type: ${type}`);
  let result;
  if (type === "history") result = await historyReport(req, patientId);
  else if (type === "labs") result = await labsReport(req, patientId, institutionId);
  else if (type === "clinical-summary") result = await clinicalSummaryReport(req, patientId);
  else if (type === "audit") result = await auditReport(req);
  else result = await populationReport();

  await auditRequest(req, {
    action: "report_generated",
    resourceType: "report",
    metadata: { type, format, patientId: patientId || null },
  });

  const normalized = format.toLowerCase();
  if (normalized === "json") {
    return { contentType: "application/json", filename: `${type}.json`, body: JSON.stringify(result.fhir || result.json || result.summary || result.csv, null, 2) };
  }
  if (normalized === "csv") {
    if (!result.csv) throw httpError(400, "CSV is not available for this report");
    return { contentType: "text/csv; charset=utf-8", filename: `${type}.csv`, body: result.csv };
  }
  if (normalized === "fhir") {
    if (!result.fhir) throw httpError(400, "FHIR is not available for this report");
    return { contentType: "application/fhir+json", filename: `${type}.fhir.json`, body: JSON.stringify(result.fhir, null, 2) };
  }
  if (normalized === "text" || normalized === "clipboard") {
    return { contentType: "text/plain; charset=utf-8", filename: `${type}.txt`, body: result.clipboard || result.lines.join("\n") };
  }
  return { contentType: "application/pdf", filename: `${type}.pdf`, body: await createTextPdf(result.title, result.lines, { subtitle: result.subtitle }) };
}
